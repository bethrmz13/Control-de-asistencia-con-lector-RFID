    public void ingresar() {
        String usuario = jtxtUsuario.getText().trim();
        String clave = new String(jpwdClave.getPassword());

        if (usuario.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Ingrese el usuario");
            jtxtUsuario.requestFocus();
            return;
        }
        if (clave.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Ingrese la clave");
            jpwdClave.requestFocus();
            return;
        }

        Usuario u = UsuarioDAO.validar(usuario, clave);
        if (u == null) {
            JOptionPane.showMessageDialog(null, "Usuario o clave incorrectos");
            jpwdClave.setText("");
            jpwdClave.requestFocus();
            return;
        }

        VentanaPrincipal principal = new VentanaPrincipal(u);
        principal.setVisible(true);
        this.dispose();
    }

